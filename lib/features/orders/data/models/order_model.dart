import 'dart:convert';
import '../../domain/entities/order.dart';
import '../../../cart/data/models/cart_item_model.dart';
import '../../../cart/domain/entities/cart_item.dart';

class OrderModel extends Order {
  const OrderModel({
    required super.id,
    required super.orderNumber,
    required super.items,
    required super.subtotal,
    required super.shippingCost,
    required super.taxAmount,
    required super.totalAmount,
    required super.status,
    required super.paymentStatus,
    required super.shippingAddress,
    required super.billingAddress,
    required super.paymentMethod,
    required super.orderDate,
    super.estimatedDelivery,
      super.deliveredDate,
      super.trackingNumber,
      super.trackingPage,
      super.deliveryState,
    super.deliveryCarrier,
    super.currentLocation,
    super.shippedDate,
    super.outForDeliveryDate,
    super.deliveryNotes,
    super.notes,
    required super.customerId,
    required super.customerName,
    required super.customerEmail,
    required super.customerPhone,
    super.state,
    super.stateDisplay,
    super.currency,
    super.orderLineCount,
    super.deliveryStatus,
    super.invoiceStatus,
    super.validityDate,
    super.partnerShipping,
    super.shippingMethod,
  });

  factory OrderModel.fromJson(Map<String, dynamic> json) {
    return OrderModel(
      id: json['id'] ?? '',
      orderNumber: json['orderNumber'] ?? '',
      items: List<CartItemModel>.from(
        (json['items'] ?? []).map((x) => CartItemModel.fromJson(x)),
      ),
      subtotal: (json['subtotal'] ?? 0.0).toDouble(),
      shippingCost: (json['shippingCost'] ?? 0.0).toDouble(),
      taxAmount: (json['taxAmount'] ?? 0.0).toDouble(),
      totalAmount: (json['totalAmount'] ?? 0.0).toDouble(),
      status: OrderStatus.values.firstWhere(
        (e) => e.toString().split('.').last == json['status'],
        orElse: () => OrderStatus.pending,
      ),
      paymentStatus: PaymentStatus.values.firstWhere(
        (e) => e.toString().split('.').last == json['paymentStatus'],
        orElse: () => PaymentStatus.pending,
      ),
      shippingAddress: json['shippingAddress'] ?? '',
      billingAddress: json['billingAddress'] ?? '',
      paymentMethod: json['paymentMethod'] ?? '',
      orderDate: DateTime.parse(json['orderDate'] ?? DateTime.now().toIso8601String()),
      estimatedDelivery: json['estimatedDelivery'] != null
          ? DateTime.parse(json['estimatedDelivery'])
          : null,
      deliveredDate: json['deliveredDate'] != null
          ? DateTime.parse(json['deliveredDate'])
          : null,
      trackingNumber: json['trackingNumber'],
      trackingPage: json['trackingPage'],
      deliveryState: json['deliveryState'] != null
          ? DeliveryState.values.firstWhere(
              (e) => e.toString().split('.').last == json['deliveryState'],
              orElse: () => DeliveryState.notStarted,
            )
          : null,
      deliveryCarrier: json['deliveryCarrier'],
      currentLocation: json['currentLocation'],
      shippedDate: json['shippedDate'] != null
          ? DateTime.parse(json['shippedDate'])
          : null,
      outForDeliveryDate: json['outForDeliveryDate'] != null
          ? DateTime.parse(json['outForDeliveryDate'])
          : null,
      deliveryNotes: json['deliveryNotes'],
      notes: json['notes'],
      customerId: json['customerId'] ?? '',
      customerName: json['customerName'] ?? '',
      customerEmail: json['customerEmail'] ?? '',
      customerPhone: json['customerPhone'] ?? '',
      state: json['state']?.toString(),
      stateDisplay: json['stateDisplay']?.toString(),
      currency: json['currency']?.toString(),
      orderLineCount: json['orderLineCount'] != null ? (json['orderLineCount'] as num).toInt() : null,
      deliveryStatus: json['deliveryStatus']?.toString(),
      invoiceStatus: json['invoiceStatus']?.toString(),
      validityDate: json['validityDate'] != null ? DateTime.tryParse(json['validityDate'].toString()) : null,
      partnerShipping: json['partnerShipping'] is Map<String, dynamic> ? Map<String, dynamic>.from(json['partnerShipping']) : null,
      shippingMethod: json['shippingMethod'] is Map<String, dynamic> ? Map<String, dynamic>.from(json['shippingMethod']) : null,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'orderNumber': orderNumber,
      'items': items.map((x) => (x as CartItemModel).toJson()).toList(),
      'subtotal': subtotal,
      'shippingCost': shippingCost,
      'taxAmount': taxAmount,
      'totalAmount': totalAmount,
      'status': status.toString().split('.').last,
      'paymentStatus': paymentStatus.toString().split('.').last,
      'shippingAddress': shippingAddress,
      'billingAddress': billingAddress,
      'paymentMethod': paymentMethod,
      'orderDate': orderDate.toIso8601String(),
      'estimatedDelivery': estimatedDelivery?.toIso8601String(),
      'deliveredDate': deliveredDate?.toIso8601String(),
      'trackingNumber': trackingNumber,
      'trackingPage': trackingPage,
      'deliveryState': deliveryState?.toString().split('.').last,
      'deliveryCarrier': deliveryCarrier,
      'currentLocation': currentLocation,
      'shippedDate': shippedDate?.toIso8601String(),
      'outForDeliveryDate': outForDeliveryDate?.toIso8601String(),
      'deliveryNotes': deliveryNotes,
      'notes': notes,
      'customerId': customerId,
      'customerName': customerName,
      'customerEmail': customerEmail,
      'customerPhone': customerPhone,
      'state': state,
      'stateDisplay': stateDisplay,
      'currency': currency,
      'orderLineCount': orderLineCount,
      'deliveryStatus': deliveryStatus,
      'invoiceStatus': invoiceStatus,
      'validityDate': validityDate?.toIso8601String(),
      'partnerShipping': partnerShipping,
      'shippingMethod': shippingMethod,
    };
  }

  factory OrderModel.fromEntity(Order order) {
    return OrderModel(
      id: order.id,
      orderNumber: order.orderNumber,
      items: order.items.map((item) => CartItemModel.fromEntity(item)).toList(),
      subtotal: order.subtotal,
      shippingCost: order.shippingCost,
      taxAmount: order.taxAmount,
      totalAmount: order.totalAmount,
      status: order.status,
      paymentStatus: order.paymentStatus,
      shippingAddress: order.shippingAddress,
      billingAddress: order.billingAddress,
      paymentMethod: order.paymentMethod,
      orderDate: order.orderDate,
      estimatedDelivery: order.estimatedDelivery,
      deliveredDate: order.deliveredDate,
      trackingNumber: order.trackingNumber,
      trackingPage: order.trackingPage,
      deliveryState: order.deliveryState,
      deliveryCarrier: order.deliveryCarrier,
      currentLocation: order.currentLocation,
      shippedDate: order.shippedDate,
      outForDeliveryDate: order.outForDeliveryDate,
      deliveryNotes: order.deliveryNotes,
      notes: order.notes,
      customerId: order.customerId,
      customerName: order.customerName,
      customerEmail: order.customerEmail,
      customerPhone: order.customerPhone,
      state: order.state,
      stateDisplay: order.stateDisplay,
      currency: order.currency,
      orderLineCount: order.orderLineCount,
      deliveryStatus: order.deliveryStatus,
      invoiceStatus: order.invoiceStatus,
      validityDate: order.validityDate,
      partnerShipping: order.partnerShipping,
      shippingMethod: order.shippingMethod,
    );
  }

  @override
  OrderModel copyWith({
    String? id,
    String? orderNumber,
    List<CartItem>? items,
    double? subtotal,
    double? shippingCost,
    double? taxAmount,
    double? totalAmount,
    OrderStatus? status,
    PaymentStatus? paymentStatus,
    String? shippingAddress,
    String? billingAddress,
    String? paymentMethod,
    DateTime? orderDate,
    DateTime? estimatedDelivery,
    DateTime? deliveredDate,
    String? trackingNumber,
    String? trackingPage,
    DeliveryState? deliveryState,
    String? deliveryCarrier,
    String? currentLocation,
    DateTime? shippedDate,
    DateTime? outForDeliveryDate,
    String? deliveryNotes,
    String? notes,
    String? customerId,
    String? customerName,
    String? customerEmail,
    String? customerPhone,
    String? state,
    String? stateDisplay,
    String? currency,
    int? orderLineCount,
    String? deliveryStatus,
    String? invoiceStatus,
    DateTime? validityDate,
    Map<String, dynamic>? partnerShipping,
    Map<String, dynamic>? shippingMethod,
  }) {
    return OrderModel(
      id: id ?? this.id,
      orderNumber: orderNumber ?? this.orderNumber,
      items: items ?? this.items,
      subtotal: subtotal ?? this.subtotal,
      shippingCost: shippingCost ?? this.shippingCost,
      taxAmount: taxAmount ?? this.taxAmount,
      totalAmount: totalAmount ?? this.totalAmount,
      status: status ?? this.status,
      paymentStatus: paymentStatus ?? this.paymentStatus,
      shippingAddress: shippingAddress ?? this.shippingAddress,
      billingAddress: billingAddress ?? this.billingAddress,
      paymentMethod: paymentMethod ?? this.paymentMethod,
      orderDate: orderDate ?? this.orderDate,
      estimatedDelivery: estimatedDelivery ?? this.estimatedDelivery,
      deliveredDate: deliveredDate ?? this.deliveredDate,
      trackingNumber: trackingNumber ?? this.trackingNumber,
      trackingPage: trackingPage ?? this.trackingPage,
      deliveryState: deliveryState ?? this.deliveryState,
      deliveryCarrier: deliveryCarrier ?? this.deliveryCarrier,
      currentLocation: currentLocation ?? this.currentLocation,
      shippedDate: shippedDate ?? this.shippedDate,
      outForDeliveryDate: outForDeliveryDate ?? this.outForDeliveryDate,
      deliveryNotes: deliveryNotes ?? this.deliveryNotes,
      notes: notes ?? this.notes,
      customerId: customerId ?? this.customerId,
      customerName: customerName ?? this.customerName,
      customerEmail: customerEmail ?? this.customerEmail,
      customerPhone: customerPhone ?? this.customerPhone,
      state: state ?? this.state,
      stateDisplay: stateDisplay ?? this.stateDisplay,
      currency: currency ?? this.currency,
      orderLineCount: orderLineCount ?? this.orderLineCount,
      deliveryStatus: deliveryStatus ?? this.deliveryStatus,
      invoiceStatus: invoiceStatus ?? this.invoiceStatus,
      validityDate: validityDate ?? this.validityDate,
      partnerShipping: partnerShipping ?? this.partnerShipping,
      shippingMethod: shippingMethod ?? this.shippingMethod,
    );
  }
}

// JSON serialization helpers
String orderModelToJson(OrderModel order) => json.encode(order.toJson());
OrderModel orderModelFromJson(String str) => OrderModel.fromJson(json.decode(str));

String orderModelListToJson(List<OrderModel> orders) => 
    json.encode(orders.map((x) => x.toJson()).toList());

List<OrderModel> orderModelListFromJson(String str) => 
    List<OrderModel>.from(json.decode(str).map((x) => OrderModel.fromJson(x)));
